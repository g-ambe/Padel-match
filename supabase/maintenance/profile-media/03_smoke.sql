BEGIN;
-- 専用の一時プロフィールだけ。秘密値の照合設定を含め、外側のROLLBACKで全て戻す。
DO $$
DECLARE actor uuid:=gen_random_uuid(); other_actor uuid:=gen_random_uuid(); profile uuid:=gen_random_uuid();
 request1 uuid:=gen_random_uuid(); request2 uuid:=gen_random_uuid(); request3 uuid:=gen_random_uuid(); request4 uuid:=gen_random_uuid();
 proof text:=repeat('a',64); m jsonb; old_key text; ticket uuid; denied boolean;
BEGIN
 INSERT INTO public.player_profiles(id,display_name,linked_auth_user_id,is_active) VALUES(profile,'TASK01一時検証',actor,true);
 UPDATE profile_media_private.settings SET commit_secret_sha256=sha256(convert_to(proof,'UTF8'));
 PERFORM set_config('request.jwt.claim.sub',actor::text,true);
 PERFORM set_config('request.jwt.claims',json_build_object('sub',actor,'role','authenticated')::text,true);
 SET LOCAL ROLE authenticated;
 m:=public.save_my_instagram(profile,0,' @demo_player ',public.profile_media_attempt());
 IF m->>'instagram_username'<>'demo_player' THEN RAISE EXCEPTION '0048_instagram_normalization_failed'; END IF;
 m:=public.prepare_profile_image(profile,request1,0,'upload',public.profile_media_attempt(),repeat('0',64));
 denied:=false;
 BEGIN PERFORM public.commit_profile_image(profile,request1,repeat('b',64)); EXCEPTION WHEN insufficient_privilege THEN denied:=true; END;
 IF NOT denied THEN RAISE EXCEPTION '0048_worker_proof_not_required'; END IF;
 m:=public.commit_profile_image(profile,request1,proof);old_key:=m->>'avatar_key';
 IF (m->>'avatar_version')::int<>1 OR public.claim_profile_media_gc(old_key,proof) THEN RAISE EXCEPTION '0048_initial_commit_or_reference_guard_failed'; END IF;
 -- Worker秘密値の復旧・再発行は照合値だけを替え、画像参照/版を変更しない。
 SET LOCAL ROLE postgres;
 UPDATE profile_media_private.settings SET commit_secret_sha256=sha256(convert_to(repeat('b',64),'UTF8'));
 SET LOCAL ROLE authenticated;denied:=false;
 BEGIN PERFORM public.commit_profile_image(profile,request1,proof); EXCEPTION WHEN insufficient_privilege THEN denied:=true; END;
 IF NOT denied OR public.claim_profile_media_gc(old_key,repeat('b',64)) OR (SELECT avatar_version FROM public.player_profile_private WHERE profile_id=profile)<>1 THEN RAISE EXCEPTION '0048_proof_rotation_reference_changed'; END IF;
 SET LOCAL ROLE postgres;
 UPDATE profile_media_private.settings SET commit_secret_sha256=sha256(convert_to(proof,'UTF8'));
 SET LOCAL ROLE authenticated;
 m:=public.commit_profile_image(profile,request1,proof);
 IF (m->>'avatar_version')::int<>1 THEN RAISE EXCEPTION '0048_retry_not_idempotent'; END IF;
 PERFORM public.prepare_profile_image(profile,request2,1,'upload',public.profile_media_attempt(),repeat('0',64));
 PERFORM public.abort_profile_image(profile,request2,proof);
 IF (SELECT avatar_key FROM public.player_profile_private WHERE profile_id=profile) IS DISTINCT FROM old_key THEN RAISE EXCEPTION '0048_abort_lost_old_image'; END IF;
 PERFORM public.prepare_profile_image(profile,request3,1,'upload',public.profile_media_attempt(),repeat('0',64));
 m:=public.commit_profile_image(profile,request3,proof);
 IF m->>'avatar_key'=old_key OR NOT public.claim_profile_media_gc(old_key,proof) THEN RAISE EXCEPTION '0048_replace_or_gc_failed'; END IF;
 PERFORM public.finish_profile_media_gc(old_key,proof);
 PERFORM public.prepare_profile_image(profile,request4,2,'delete',public.profile_media_attempt(),NULL);
 m:=public.commit_profile_image(profile,request4,proof);
 IF m->>'avatar_key' IS NOT NULL THEN RAISE EXCEPTION '0048_delete_failed'; END IF;
 ticket:=public.profile_media_attempt();denied:=false;
 BEGIN PERFORM public.prepare_profile_image(profile,gen_random_uuid(),3,'upload',ticket,repeat('0',64)); EXCEPTION WHEN SQLSTATE 'PT429' THEN denied:=true; END;
 IF NOT denied THEN RAISE EXCEPTION '0048_quota_not_enforced'; END IF;
 m:=public.save_my_instagram(profile,1,'',public.profile_media_attempt());
 IF m->>'instagram_username' IS NOT NULL THEN RAISE EXCEPTION '0048_instagram_delete_failed'; END IF;
 SET LOCAL ROLE postgres;
 PERFORM set_config('request.jwt.claim.sub',other_actor::text,true);
 PERFORM set_config('request.jwt.claims',json_build_object('sub',other_actor,'role','authenticated')::text,true);
 SET LOCAL ROLE authenticated;
 IF EXISTS(SELECT 1 FROM public.player_profile_private WHERE profile_id=profile) THEN RAISE EXCEPTION '0048_private_data_exposed'; END IF;
 denied:=false;
 BEGIN PERFORM public.save_my_instagram(profile,2,'bad',public.profile_media_attempt()); EXCEPTION WHEN insufficient_privilege THEN denied:=true; END;
 IF NOT denied THEN RAISE EXCEPTION '0048_other_user_update_allowed'; END IF;
 SET LOCAL ROLE anon;denied:=false;
 BEGIN PERFORM public.profile_media_attempt(); EXCEPTION WHEN insufficient_privilege THEN denied:=true; END;
 IF NOT denied THEN RAISE EXCEPTION '0048_anon_execute_allowed'; END IF;
 SET LOCAL ROLE postgres;
END; $$;
ROLLBACK;
